def class_name(name: str) -> str:
    return "".join(part.capitalize() for part in name.split("_")) + "Tool"


def dump(data: object) -> str:
    return yaml.safe_dump(data, allow_unicode=True, sort_keys=False, width=1000)


def tool_yaml(spec: dict) -> dict:
    data: dict = {
        "identity": {"name": spec["name"], "author": AUTHOR, "label": spec["label"]},
        "description": {"human": spec["human"], "llm": spec["llm"]},
        "parameters": spec["params"],
    }
    if spec.get("output"):
        data["output_schema"] = {"type": "object", "properties": spec["output"]}
    data["extra"] = {"python": {"source": f"tools/{spec['name']}.py"}}
    return data


def tool_py(spec: dict) -> str:
    return f'''{HEADER}from collections.abc import Generator
from typing import Any

from dify_plugin import Tool
from dify_plugin.entities.tool import ToolInvokeMessage

from useapi_notebook import runner


class {class_name(spec["name"])}(Tool):
    def _invoke(self, tool_parameters: dict[str, Any]) -> Generator[ToolInvokeMessage, None, None]:
        yield from runner.invoke(self, "{spec["name"]}", tool_parameters)
'''


def main() -> None:
    tools_dir = ROOT / "tools"
    tools_dir.mkdir(exist_ok=True)
    names = [t["name"] for t in TOOLS]
    if len(names) != len(set(names)):
        raise SystemExit("duplicate tool names")
    for old in list(tools_dir.glob("*.yaml")) + list(tools_dir.glob("*.py")):
        if old.stem not in names:
            old.unlink()
    for spec in TOOLS:
        (tools_dir / f"{spec['name']}.yaml").write_text(HEADER + dump(tool_yaml(spec)), encoding="utf-8")
        (tools_dir / f"{spec['name']}.py").write_text(tool_py(spec), encoding="utf-8")
    provider = {
        "identity": {
            "author": AUTHOR,
            "name": PROVIDER,
            "label": PROVIDER_LABEL,
            "description": PROVIDER_DESCRIPTION,
            "icon": "icon.png",
            "tags": ["productivity", "education", "rag"],
        },
        "credentials_for_provider": CREDENTIALS,
        "tools": [f"tools/{n}.yaml" for n in names],
        "extra": {"python": {"source": "provider/notebooklm_useapi.py"}},
    }
    (ROOT / "provider" / f"{PROVIDER}.yaml").write_text(HEADER + dump(provider), encoding="utf-8")
    print(f"wrote {len(names)} tools")


if __name__ == "__main__":
    main()
